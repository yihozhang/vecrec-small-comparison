"""Dataset registry for the minimap2 VecRec comparison harness.

A Dataset pairs a reference FASTA with a reads FASTQ and records how to
(re)produce it:

  - kind="synthetic": reproducibly regenerated by make_datasets.py (artificial
    sequences with tunable params).
  - kind="real": a committed/vendored file, or fetched on demand (real biology).

`fair` marks datasets whose natural minimap2 regime is no-band / no-z-drop /
no-approx (VecRec's regime, DP sizes > 256) — i.e. a fair perf comparison.

scenarios.py references these by name. Extending: add a Dataset entry here (and,
for synthetic sets, a recipe in make_datasets.py). All paths live under
end_to_end_baselines/data/ (the single data folder).
"""
from __future__ import annotations

import pathlib
from dataclasses import dataclass

REPO = pathlib.Path(__file__).resolve().parents[2]
DATA = REPO / "end_to_end_baselines" / "data"


@dataclass(frozen=True)
class Dataset:
    name: str
    ref: pathlib.Path        # reference FASTA
    reads: pathlib.Path      # reads FASTQ
    kind: str                # "synthetic" | "real"
    fair: bool               # natural regime is no-band/no-zdrop (fair for VecRec)
    desc: str
    make: str | None = None  # how to (re)produce ref+reads if missing

    def present(self) -> bool:
        return self.ref.exists() and self.reads.exists()


